<?php

/**
 * Русское склонение существительного по числительному.
 *
 * plural(1, 'банка', 'банки', 'банок')  → 'банка'
 * plural(2, 'банка', 'банки', 'банок')  → 'банки'
 * plural(5, 'банка', 'банки', 'банок')  → 'банок'
 * plural(19, 'сорт', 'сорта', 'сортов') → 'сортов'
 * plural(21, 'сорт', 'сорта', 'сортов') → 'сорт'
 * plural(22, 'сорт', 'сорта', 'сортов') → 'сорта'
 */
if (!function_exists('plural')) {
    function plural(int $n, string $one, string $few, string $many): string
    {
        $mod10  = $n % 10;
        $mod100 = $n % 100;

        if ($mod100 >= 11 && $mod100 <= 19) return $many;  // 11–19 → банок
        if ($mod10 === 1)                   return $one;    // 1, 21, 31 → банка
        if ($mod10 >= 2 && $mod10 <= 4)     return $few;    // 2–4, 22–24 → банки
        return $many;                                        // 0, 5–9, 10, 25–30 → банок
    }
}